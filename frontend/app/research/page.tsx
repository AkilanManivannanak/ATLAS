"use client";

import { useMemo, useState } from "react";
import { HBarChart } from "@/components/charts";
import { ErrorBox, Header, Panel, SyntheticBadge, useAsync } from "@/components/ui";
import { api } from "@/lib/api";
import { pct } from "@/lib/format";

type FcRow = { model: string; horizon: string; split: string; mae: number; rmse: number; mase: number; crps_approx: number; interval_coverage: number; interval_mean_width: number; interval_nominal: number; n_test: number };
type Forecast = { results: FcRow[]; splits: Record<string, unknown>; uncertainty_method: string; target: string; manifest?: Record<string, unknown> };
type Game = { strategies: string[]; seeds: number[]; deviations: { profile: string; deviation: string; focal: string; mean_gain_minor: number; ci95: [number, number]; profitable_deviation: boolean; n_seeds: number }[];
  profiles: Record<string, { verdict: string; mean_system_cost_minor: number; claim_scope: string }>; socially_best_profile: string; method: string };
type Netting = { rows: { obligations: number; instances: number; mean_gap: number; max_gap: number; share_heuristic_optimal: number; heuristic_ms_mean: number; milp_ms_mean: number; milp_optimal_share: number }[] };
type Auction = { system: { stress: string; mechanism: string; settled_mean: number; settled_diff_ci: number[]; avg_rate_cbp: number | null; principal_mean_minor: number | null }[];
  incentives: { stress: string; mechanism: string; shade_bp: number; mean_gain_minor: number; ci95: number[]; share_profitable: number; profitable_deviation: boolean }[] };
type SafeRL = { summary: { stress: string; arm: string; held_out_stress: boolean; cost: number[]; cost_diff_vs_mpc: number[]; settled: number[]; safety_rejection_rate: number; wins_vs_mpc: number }[] };
type Scaling = { rows: { institutions: number; payments: number; events: number; simulate_s: number; replay_s: number; events_per_s: number; peak_rss_mb: number; replay_verified: boolean }[] };
type Bench = { name: string; benchmark_version: string; config: Record<string, unknown>; manifest: Record<string, unknown> };

export default function Research() {
  const fc = useAsync(() => api<Forecast>("/research/forecasting"), []);
  const game = useAsync(() => api<Game>("/research/game"), []);
  const net = useAsync(() => api<Netting>("/research/netting_optimality"), []);
  const bench = useAsync(() => api<Bench>("/benchmarks/standard"), []);
  const auction = useAsync(() => api<Auction>("/research/auction"), []);
  const rl = useAsync(() => api<SafeRL>("/research/safe_rl"), []);
  const scaling = useAsync(() => api<Scaling>("/research/scaling"), []);
  const [split, setSplit] = useState("test_in_distribution");
  const [horizon, setHorizon] = useState("1h");
  const rows = useMemo(() => (fc.data?.results ?? []).filter((r) => r.split === split && r.horizon === horizon).sort((a, b) => a.mae - b.mae), [fc.data, split, horizon]);
  return (
    <>
      <Header title="Research Studio" subtitle="Reproducible experiment artifacts generated by this codebase on synthetic data: forecasting, strategic behaviour, algorithm optimality and the NEXUS-PAY benchmark manifest. Negative and inconclusive findings are shown as-is." right={<SyntheticBadge />} />
      <ErrorBox error={fc.error || game.error || net.error || bench.error || auction.error || rl.error || scaling.error} />
      <div className="grid g21">
        <Panel title="Probabilistic forecasting · net outflow per bank per 15 min" tag={fc.data?.uncertainty_method}>
          <div className="ctl" style={{ marginBottom: 10 }}>
            <label>Test split<select value={split} onChange={(e) => setSplit(e.target.value)}><option value="test_in_distribution">in-distribution days</option><option value="test_out_of_distribution">shifted config (OOD)</option></select></label>
            <label>Horizon<select value={horizon} onChange={(e) => setHorizon(e.target.value)}>{["15m", "30m", "1h", "4h"].map((h) => <option key={h}>{h}</option>)}</select></label>
          </div>
          <table className="t">
            <thead><tr><th>Model</th><th>MAE</th><th>RMSE</th><th>MASE</th><th>CRPS≈</th><th>90% PI coverage</th><th>PI width</th></tr></thead>
            <tbody>
              {rows.map((r) => (
                <tr key={r.model}>
                  <td>{r.model}</td><td>${(r.mae / 1e6).toFixed(2)}M</td><td>${(r.rmse / 1e6).toFixed(2)}M</td><td className={r.mase < 1 ? "ok" : "bad"}>{r.mase.toFixed(3)}</td>
                  <td>${(r.crps_approx / 1e6).toFixed(2)}M</td>
                  <td className={Math.abs(r.interval_coverage - r.interval_nominal) < 0.03 ? "ok" : "warn"}>{pct(r.interval_coverage, 1)}</td><td>${(r.interval_mean_width / 1e6).toFixed(1)}M</td>
                </tr>
              ))}
            </tbody>
          </table>
          <p className="note">Whole simulated days are split train / validation / test; no test-day bucket is seen in training. Intervals come from split-conformal residuals on validation days, and coverage is measured on test days. Under distribution shift, coverage falls well below nominal. That is the expected and reported failure mode, not a bug.</p>
        </Panel>
        <Panel title="Benchmark manifest" tag={bench.data?.benchmark_version}>
          <dl className="kv">
            {bench.data && Object.entries(bench.data.manifest).map(([k, v]) => [<dt key={k}>{k}</dt>, <dd key={k + "v"} style={{ whiteSpace: "normal" }}>{String(v)}</dd>])}
          </dl>
        </Panel>
      </div>
      <div className="grid g2" style={{ marginTop: 14 }}>
        <Panel title="Strategic behaviour · empirical liquidity game" tag={game.data ? `${game.data.seeds.length} paired seeds` : ""}>
          <table className="t">
            <thead><tr><th>Profile (all banks)</th><th>Verdict</th><th>System cost</th></tr></thead>
            <tbody>
              {game.data && Object.entries(game.data.profiles).map(([k, v]) => (
                <tr key={k}><td>{k}{k === game.data!.socially_best_profile ? " ★" : ""}</td>
                  <td><span className={`pill ${v.verdict === "unstable" ? "bad" : v.verdict === "inconclusive" ? "warn" : "ok"}`}>{v.verdict}</span></td>
                  <td>${(v.mean_system_cost_minor / 1e8).toFixed(2)}M</td></tr>
              ))}
            </tbody>
          </table>
          <h3 style={{ marginTop: 14, fontSize: 11, color: "var(--muted)", letterSpacing: "0.12em", textTransform: "uppercase" }}>Unilateral deviation gain for focal bank (95% CI)</h3>
          <div className="scroll" style={{ maxHeight: 260 }}>
            <table className="t">
              <thead><tr><th>Profile</th><th>Deviate to</th><th>Focal</th><th>Mean gain</th><th>CI95</th></tr></thead>
              <tbody>
                {game.data?.deviations.map((d, i) => (
                  <tr key={i}><td>{d.profile}</td><td>{d.deviation}</td><td>{d.focal}</td><td className={d.profitable_deviation ? "bad" : "muted"}>${(d.mean_gain_minor / 1e8).toFixed(3)}M</td>
                    <td className="dim">[{(d.ci95[0] / 1e8).toFixed(3)}, {(d.ci95[1] / 1e8).toFixed(3)}]</td></tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="note">{game.data?.method}. Verdicts cover only the tested focal banks and deviations; they are not proofs of Nash equilibrium. ★ = lowest system cost.</p>
        </Panel>
        <Panel title="Netting algorithm optimality gap" tag="heuristic vs exact HiGHS MILP">
          <HBarChart rows={(net.data?.rows ?? []).map((r) => ({ label: `${r.obligations} obligations`, value: r.mean_gap * 100, color: "var(--warn)" }))} format={(v) => `${v.toFixed(2)}%`} />
          <table className="t" style={{ marginTop: 8 }}>
            <thead><tr><th>Queue size</th><th>Mean gap</th><th>Max gap</th><th>Heuristic optimal</th><th>Heuristic ms</th><th>MILP ms</th></tr></thead>
            <tbody>
              {net.data?.rows.map((r) => (
                <tr key={r.obligations}><td>{r.obligations}</td><td>{(r.mean_gap * 100).toFixed(2)}%</td><td>{(r.max_gap * 100).toFixed(2)}%</td><td>{pct(r.share_heuristic_optimal, 0)}</td>
                  <td>{r.heuristic_ms_mean.toFixed(1)}</td><td>{r.milp_ms_mean.toFixed(1)}</td></tr>
              ))}
            </tbody>
          </table>
          <p className="note">Gap = 1 − heuristic settled value / optimal settled value on random gridlocked queues. Both outputs are re-verified in exact integer arithmetic before use.</p>
        </Panel>
      </div>
      <div className="grid g3" style={{ marginTop: 14 }}>
        <Panel title="Liquidity auction (E4)" tag="paired seeds">
          <table className="t">
            <thead><tr><th>Stress</th><th>Mechanism</th><th>Settled</th><th>Δ vs none</th><th>Rate</th></tr></thead>
            <tbody>{auction.data?.system.map((r, i) => (
              <tr key={i}><td>{r.stress}</td><td>{r.mechanism}</td><td>{pct(r.settled_mean)}</td>
                <td className={r.mechanism === "none" ? "dim" : r.settled_diff_ci[1] > 0 ? "ok" : "muted"}>{r.mechanism === "none" ? "—" : `${(r.settled_diff_ci[0] * 100).toFixed(2)}pp`}</td>
                <td>{r.avg_rate_cbp == null ? "—" : `${(r.avg_rate_cbp / 100).toFixed(3)}bp`}</td></tr>))}</tbody>
          </table>
          <p className="note">Ask inflation by a top lender is profitable (CI above zero) in {auction.data?.incentives.filter((i) => i.profitable_deviation).length ?? "—"} of {auction.data?.incentives.length ?? "—"} mechanism × stress × shading cells. Neither rule is assumed incentive compatible.</p>
        </Panel>
        <Panel title="Safe RL vs MPC (E7)" tag="held-out days">
          <table className="t">
            <thead><tr><th>Stress</th><th>Arm</th><th>Δ cost vs MPC</th><th>Rejected</th><th>Wins</th></tr></thead>
            <tbody>{rl.data?.summary.filter((s) => s.arm !== "mpc").map((s, i) => (
              <tr key={i}><td>{s.stress}{s.held_out_stress ? " *" : ""}</td><td>{s.arm}</td>
                <td className={s.cost_diff_vs_mpc[2] < 0 ? "ok" : s.cost_diff_vs_mpc[1] > 0 ? "bad" : "muted"}>${(s.cost_diff_vs_mpc[0] / 1e8).toFixed(2)}M</td>
                <td>{pct(s.safety_rejection_rate, 1)}</td><td>{s.wins_vs_mpc}/10</td></tr>))}</tbody>
          </table>
          <p className="note">* stress never seen in training. Green/red = 95% CI excludes zero.</p>
        </Panel>
        <Panel title="Scaling" tag="one CPU core">
          <table className="t">
            <thead><tr><th>Banks</th><th>Payments</th><th>Sim s</th><th>Events/s</th><th>RSS</th></tr></thead>
            <tbody>{scaling.data?.rows.map((r) => (
              <tr key={r.payments}><td>{r.institutions}</td><td>{r.payments.toLocaleString()}</td><td>{r.simulate_s.toFixed(1)}</td><td>{Math.round(r.events_per_s).toLocaleString()}</td><td>{Math.round(r.peak_rss_mb)} MB</td></tr>))}</tbody>
          </table>
          <p className="note">Every row's ledger is replayed from its event log and verified.</p>
        </Panel>
      </div>
    </>
  );
}
